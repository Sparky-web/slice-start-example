/**
 * Builds `dist/theme.css` for Tailwind v4 from W3C DTCG token files exported from Figma.
 *
 * Source convention (matches Figma native variable export and the Obra shadcn/ui kit):
 * - `src/primitives.tokens.json` — raw palette and scales, never used directly in code;
 * - `src/theme.<mode>.tokens.json` — semantic colors per mode, `light` is the default mode.
 *
 * Run with `--check` in CI to fail when the committed CSS is out of sync with the tokens.
 */
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

import StyleDictionary from 'style-dictionary'

interface Dimension { value: number; unit: string }
interface Color { colorSpace: string; components: number[]; alpha?: number }
interface Shadow { color: Color; offsetX: Dimension; offsetY: Dimension; blur: Dimension; spread: Dimension }
interface Token { path: string[]; $type?: string; $value: unknown }

const root = join(import.meta.dirname, '..')
const srcDir = join(root, 'src')
const outFile = join(root, 'dist', 'theme.css')
const DEFAULT_MODE = 'light'

const dimension = (value: Dimension) => `${String(value.value)}${value.unit}`

const color = ({ colorSpace, components, alpha }: Color) => {
  const channels = components.join(' ')
  const space = colorSpace === 'srgb' ? 'rgb' : colorSpace
  const values = colorSpace === 'srgb' ? components.map((part) => Math.round(part * 255)).join(' ') : channels
  return alpha === undefined ? `${space}(${values})` : `${space}(${values} / ${String(alpha)})`
}

const shadow = (layers: Shadow[]) =>
  layers
    .map((layer) => [layer.offsetX, layer.offsetY, layer.blur, layer.spread].map(dimension).join(' ') + ` ${color(layer.color)}`)
    .join(', ')

function toCss(token: Token): string {
  const value = token.$value
  switch (token.$type) {
    case 'color': {
      return color(value as Color)
    }
    case 'dimension': {
      return dimension(value as Dimension)
    }
    case 'shadow': {
      return shadow(value as Shadow[])
    }
    case 'fontFamily': {
      return (value as string[]).map((name) => (name.includes(' ') ? `"${name}"` : name)).join(', ')
    }
    default: {
      return String(value)
    }
  }
}

async function resolve(files: string[]): Promise<Token[]> {
  const sd = new StyleDictionary({
    source: files.map((file) => join(srcDir, file)),
    usesDtcg: true,
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: { css: {} },
  })
  const dictionary = await sd.getPlatformTokens('css')
  return dictionary.allTokens as Token[]
}

/** Maps a token path to the Tailwind v4 theme variable name. */
function themeVariable(path: string[]): string | undefined {
  const [group, name, part] = path
  if (name === undefined) return undefined
  switch (group) {
    case 'spacing':
    case 'radius':
    case 'shadow':
    case 'container':
    case 'breakpoint':
    case 'font':
    case 'font-weight': {
      return `--${group}-${name}`
    }
    case 'text': {
      return part === 'line-height' ? `--text-${name}--line-height` : `--text-${name}`
    }
    default: {
      return undefined
    }
  }
}

const files = (await readdir(srcDir)).filter((file) => file.endsWith('.tokens.json')).toSorted()
const modes = files
  .map((file) => /^theme\.(.+)\.tokens\.json$/.exec(file)?.[1])
  .filter((mode) => mode !== undefined)
  .toSorted((a, b) => (a === DEFAULT_MODE ? -1 : b === DEFAULT_MODE ? 1 : a.localeCompare(b)))

const primitives = await resolve(['primitives.tokens.json'])
const scales = primitives.flatMap((token) => {
  const name = themeVariable(token.path)
  return name ? [`  ${name}: ${toCss(token)};`] : []
})

const modeBlocks: string[] = []
let semanticNames: string[] = []
for (const mode of modes) {
  const tokens = (await resolve(['primitives.tokens.json', `theme.${mode}.tokens.json`])).filter(
    (token) => token.path[0] === 'color' && token.path.length === 2,
  )
  const semantic = tokens.filter((token) => !primitives.some((primitive) => primitive.path.join('.') === token.path.join('.')))
  semanticNames = semantic.map((token) => token.path[1] ?? '')
  const selector = mode === DEFAULT_MODE ? ':root' : `.${mode}, [data-theme="${mode}"]`
  modeBlocks.push(`${selector} {\n${semantic.map((token) => `  --${token.path[1] ?? ''}: ${toCss(token)};`).join('\n')}\n}`)
}

const css = `/* Generated by @repo/tokens from src/*.tokens.json. Do not edit: change tokens in Figma and re-export. */

@theme {
  --*: initial;
  --spacing: initial;
${scales.join('\n')}
  --default-font-family: var(--font-sans);
  --default-mono-font-family: var(--font-mono);
  --default-transition-duration: 150ms;
  --default-transition-timing-function: cubic-bezier(0.4, 0, 0.2, 1);
  --ease-out: cubic-bezier(0, 0, 0.2, 1);
  --ease-in-out: cubic-bezier(0.4, 0, 0.2, 1);
  --animate-spin: spin 1s linear infinite;
  --animate-pulse: pulse 2s cubic-bezier(0.4, 0, 0.6, 1) infinite;

  @keyframes spin {
    to {
      transform: rotate(360deg);
    }
  }

  @keyframes pulse {
    50% {
      opacity: 0.5;
    }
  }
}

@theme inline {
  --color-transparent: transparent;
  --color-current: currentcolor;
${semanticNames.map((name) => `  --color-${name}: var(--${name});`).join('\n')}
}

${modeBlocks.join('\n\n')}
`

if (process.argv.includes('--check')) {
  const current = await readFile(outFile, 'utf8').catch(() => '')
  if (current !== css) {
    console.error('dist/theme.css is out of sync with tokens. Run `pnpm tokens` and commit the result.')
    process.exit(1)
  }
  console.log('Tokens are in sync.')
} else {
  await mkdir(join(root, 'dist'), { recursive: true })
  await writeFile(outFile, css)
  console.log(`Wrote ${outFile} (${String(modes.length)} modes, ${String(scales.length + semanticNames.length)} tokens)`)
}
